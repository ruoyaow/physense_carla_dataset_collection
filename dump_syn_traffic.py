def get_actor_blueprints(world, filter, generation):
    bps = world.get_blueprint_library().filter(filter)

    if generation.lower() == "all":
        return bps

    # If the filter returns only one bp, we assume that this one needed
    # and therefore, we ignore the generation
    if len(bps) == 1:
        return bps

    try:
        int_generation = int(generation)
        # Check if generation is in available generations
        if int_generation in [1, 2, 3]:
            bps = [x for x in bps if int(x.get_attribute('generation')) == int_generation]
            return bps
        else:
            print("   Warning! Actor Generation is not valid. No actor will be spawned.")
            return []
    except:
        print("   Warning! Actor Generation is not valid. No actor will be spawned.")
        return []

def tick_with_spectator(world, ego_transform, spectator):
    world.tick()
    local_offset = carla.Location(x=-6, y=0, z=3)
    cam_loc = ego_transform.transform(local_offset)
    spectator.set_transform(carla.Transform(cam_loc, ego_transform.rotation))


seconds_lasting = 100
FPS = 5
sim_FPS = 20
ratio = sim_FPS // FPS

def main():
    argparser = argparse.ArgumentParser(
        description=__doc__)
    argparser.add_argument(
        '--path',
        type=str)
    argparser.add_argument(
        '-m', '--map',
        type=str)
    argparser.add_argument(
        '--weather',
        type=str)
    argparser.add_argument(
        '-s', '--seed',
        default=42,
        type=int)
    argparser.add_argument(
        '-sw', '--seedw',
        default=43,
        type=int)
    argparser.add_argument(
        '-n', '--number-of-vehicles',
        metavar='N',
        default=50,
        type=int,
        help='Number of vehicles (default: 50)')
    argparser.add_argument(
        '-w', '--number-of-walkers',
        metavar='W',
        default=20,
        type=int,
        help='Number of walkers (default: 20)')
    argparser.add_argument(
        '--filterv',
        metavar='PATTERN',
        default='vehicle.*',
        help='Filter vehicle model (default: "vehicle.*")')
    argparser.add_argument(
        '--generationv',
        metavar='G',
        default='All',
        help='restrict to certain vehicle generation (values: "1","2","All" - default: "All")')
    argparser.add_argument(
        '--filterw',
        metavar='PATTERN',
        default='walker.pedestrian.*',
        help='Filter pedestrian type (default: "walker.pedestrian.*")')
    argparser.add_argument(
        '--generationw',
        metavar='G',
        default='2',
        help='restrict to certain pedestrian generation (values: "1","2","All" - default: "2")')
    args = argparser.parse_args()

    actor_list = []
    other_actor_list = []
    
    vehicles_list = []
    walkers_list = []
    all_id = []
    random.seed(args.seed if args.seed is not None else int(time.time()))

    # In this tutorial script, we are going to add a vehicle to the simulation
    # and let it drive in autopilot. We will also create a camera attached to
    # that vehicle, and save all the images generated by the camera to disk.

    try:
        # First of all, we need to create the client that will send the requests
        # to the simulator. Here we'll assume the simulator is accepting
        # requests in the localhost at port 2000.
        client = carla.Client('localhost', 2000)
        client.set_timeout(10.0)

        # Once we have a client we can retrieve the world that is currently
        # running.
        world = client.get_world()

        traffic_manager = client.get_trafficmanager(8000)
        traffic_manager.set_global_distance_to_leading_vehicle(2.5)
        if args.seed is not None:
            traffic_manager.set_random_device_seed(args.seed)

        settings = world.get_settings()
        settings.synchronous_mode = True
        settings.fixed_delta_seconds = (1.0 / sim_FPS)

        world.apply_settings(settings)
        
        # 1. Generate traffic

        blueprints = get_actor_blueprints(world, args.filterv, args.generationv)
        if not blueprints:
            raise ValueError("Couldn't find any vehicles with the specified filters")
        blueprintsWalkers = get_actor_blueprints(world, args.filterw, args.generationw)
        if not blueprintsWalkers:
            raise ValueError("Couldn't find any walkers with the specified filters")

        blueprints = sorted(blueprints, key=lambda bp: bp.id)

        spawn_points = world.get_map().get_spawn_points()
        number_of_spawn_points = len(spawn_points)

        if args.number_of_vehicles < number_of_spawn_points:
            random.shuffle(spawn_points)
        elif args.number_of_vehicles > number_of_spawn_points:
            print(f'requested {args.number_of_vehicles} vehicles, but could only find {number_of_spawn_points} spawn points')
            args.number_of_vehicles = number_of_spawn_points
        # args.number_of_vehicles = number_of_spawn_points // 5
        # random.shuffle(spawn_points)
        
        SpawnActor = carla.command.SpawnActor
        SetAutopilot = carla.command.SetAutopilot
        FutureActor = carla.command.FutureActor

        # --------------
        # Spawn vehicles
        # --------------
        batch = []
        for n, transform in enumerate(spawn_points):
            if n >= args.number_of_vehicles:
                break
            blueprint = random.choice(blueprints)
            if blueprint.has_attribute('color'):
                color = random.choice(blueprint.get_attribute('color').recommended_values)
                blueprint.set_attribute('color', color)
            if blueprint.has_attribute('driver_id'):
                driver_id = random.choice(blueprint.get_attribute('driver_id').recommended_values)
                blueprint.set_attribute('driver_id', driver_id)
            blueprint.set_attribute('role_name', 'autopilot')

            # spawn the cars and set their autopilot and light state all together
            batch.append(SpawnActor(blueprint, transform)
                .then(SetAutopilot(FutureActor, True, traffic_manager.get_port())))

        for response in client.apply_batch_sync(batch, True):
            if response.error:
                print(response.error)
            else:
                vehicles_list.append(response.actor_id)

        # Set automatic vehicle lights update if specified
        all_vehicle_actors = world.get_actors(vehicles_list)
        for actor in all_vehicle_actors:
            traffic_manager.update_vehicle_lights(actor, True)
                
        # -------------
        # Spawn Walkers
        # -------------
        # some settings
        percentagePedestriansRunning = 0.0      # how many pedestrians will run
        percentagePedestriansCrossing = 0.0     # how many pedestrians will walk through the road
        if args.seedw:
            world.set_pedestrians_seed(args.seedw)
            random.seed(args.seedw)
        # 1. take all the random locations to spawn
        spawn_points = []
        for i in range(args.number_of_walkers):
            spawn_point = carla.Transform()
            loc = world.get_random_location_from_navigation()
            if (loc != None):
                spawn_point.location = loc
                spawn_points.append(spawn_point)
        # 2. we spawn the walker object
        batch = []
        walker_speed = []
        for spawn_point in spawn_points:
            walker_bp = random.choice(blueprintsWalkers)
            # set as not invincible
            if walker_bp.has_attribute('is_invincible'):
                walker_bp.set_attribute('is_invincible', 'false')
            # set the max speed
            if walker_bp.has_attribute('speed'):
                if (random.random() > percentagePedestriansRunning):
                    # walking
                    walker_speed.append(walker_bp.get_attribute('speed').recommended_values[1])
                else:
                    # running
                    walker_speed.append(walker_bp.get_attribute('speed').recommended_values[2])
            else:
                print("Walker has no speed")
                walker_speed.append(0.0)
            batch.append(SpawnActor(walker_bp, spawn_point))
        results = client.apply_batch_sync(batch, True)
        walker_speed2 = []
        for i in range(len(results)):
            if results[i].error:
                print(results[i].error)
            else:
                walkers_list.append({"id": results[i].actor_id})
                walker_speed2.append(walker_speed[i])
        walker_speed = walker_speed2
        # 3. we spawn the walker controller
        batch = []
        walker_controller_bp = world.get_blueprint_library().find('controller.ai.walker')
        for i in range(len(walkers_list)):
            batch.append(SpawnActor(walker_controller_bp, carla.Transform(), walkers_list[i]["id"]))
        results = client.apply_batch_sync(batch, True)
        for i in range(len(results)):
            if results[i].error:
                print(results[i].error)
            else:
                walkers_list[i]["con"] = results[i].actor_id
        # 4. we put together the walkers and controllers id to get the objects from their id
        for i in range(len(walkers_list)):
            all_id.append(walkers_list[i]["con"])
            all_id.append(walkers_list[i]["id"])
        all_actors = world.get_actors(all_id)

        # wait for a tick to ensure client receives the last transform of the walkers we have just created
        world.tick()

        # 5. initialize each controller and set target to walk to (list is [controler, actor, controller, actor ...])
        # set how many pedestrians can cross the road
        world.set_pedestrians_cross_factor(percentagePedestriansCrossing)
        for i in range(0, len(all_id), 2):
            # start walker
            all_actors[i].start()
            # set walk to random point
            all_actors[i].go_to_location(world.get_random_location_from_navigation())
            # max speed
            all_actors[i].set_max_speed(float(walker_speed[int(i/2)]))

        print('spawned %d vehicles and %d walkers.' % (len(vehicles_list), len(walkers_list)))

        # Example of how to use Traffic Manager parameters
        traffic_manager.global_percentage_speed_difference(30.0)

        
        # 2. Camera and ego vehicle

        # The world contains the list blueprints that we can use for adding new
        # actors into the simulation.
        blueprint_library = world.get_blueprint_library()

        # Now let's filter all the blueprints of type 'vehicle' and choose one
        # at random.
        bp = random.choice(blueprint_library.filter('dodge'))

        # A blueprint contains the list of attributes that define a vehicle's
        # instance, we can read them and modify some of them. For instance,
        # let's randomize its color.
        if bp.has_attribute('color'):
            color = random.choice(bp.get_attribute('color').recommended_values)
            bp.set_attribute('color', color)

        # Now we need to give an initial transform to the vehicle. We choose a
        # random transform from the list of recommended spawn points of the map.
        transform = random.choice(world.get_map().get_spawn_points())
        
        # Save all actors in every frame
        for npc in world.get_actors().filter('*vehicle*'):
            '''
            bb = npc.bounding_box
            dist = npc.get_transform().location.distance(vehicle.get_transform().location)

            # Filter for the vehicles within 50m
            if dist < 300:
            '''
            other_actor_list.append(npc)
        for npc in world.get_actors().filter('*pedestrian*'):
            other_actor_list.append(npc)
        # print(other_actor_list)

        # So let's tell the world to spawn the vehicle.
        vehicle = world.try_spawn_actor(bp, transform)
        while vehicle is None:
            print("Spawn ego failed, retry...")
            for _ in range(sim_FPS*2):
                world.tick()
            time.sleep(1)
            vehicle = world.try_spawn_actor(bp, transform)
        print("Spawn ego success")

        # It is important to note that the actors we create won't be destroyed
        # unless we call their "destroy" function. If we fail to call "destroy"
        # they will stay in the simulation even after we quit the Python script.
        # For that reason, we are storing all the actors we create so we can
        # destroy them afterwards.
        actor_list.append(vehicle)
        print('created %s' % vehicle.type_id)

        # Let's put the vehicle to drive around.
        time.sleep(1)
        vehicle.set_autopilot(True)

        spectator = world.get_spectator()
        # world_snapshot = world.wait_for_tick() 
        spectator.set_transform(vehicle.get_transform())

        # Let's add now a camera attached to the vehicle. Note that the
        # transform we give here is now relative to the vehicle.
        camera_bp = blueprint_library.find('sensor.camera.rgb')
        # camera_transform = carla.Transform(carla.Location(x=1.5, z=2.4))
        camera_transform = carla.Transform(carla.Location(x=2, z=1.5))
            
        image_w = camera_bp.get_attribute("image_size_x").as_int()
        image_h = camera_bp.get_attribute("image_size_y").as_int()
        fov = camera_bp.get_attribute("fov").as_float()
        
        camera = world.spawn_actor(camera_bp, camera_transform, attach_to=vehicle)
        actor_list.append(camera)
        print('created %s' % camera.type_id)
        # print(world.get_actors())

        # Now we register the function that will be called each time the sensor
        # receives an image. In this example we are saving the image to disk
        # converting the pixels to gray-scale.
        # cc = carla.ColorConverter.LogarithmicDepth
        # camera.listen(lambda image: image.save_to_disk('_out/%06d.png' % image.frame, cc))

        # camera.listen(lambda image: image.save_to_disk('_out/%06d.png' % image.frame))
        camera_frame_counter = 0
        done_dump_flag = False
        # frames_actor_info = {}
        def save_image_to_disk(image):
            nonlocal camera_frame_counter
            nonlocal done_dump_flag
            if (camera_frame_counter+1) % ratio != 0:
                camera_frame_counter += 1
                done_dump_flag = True
                return
            # nonlocal frames_actor_info
            this_frame_info = {}
            this_frame_info['ego'] = {"forward_vec": str(vehicle.get_transform().get_forward_vector()),
                                      "location": str(vehicle.get_transform().location),
                                      "velocity": str(vehicle.get_velocity()),
                                      "acceleration": str(vehicle.get_acceleration()),
                                      "angular_velocity": str(vehicle.get_angular_velocity()),
                                      "transform": str(vehicle.get_transform()),
                                      }
            this_frame_info['camera'] = {"image_w": image_w,
                                         "image_h": image_h,
                                         "fov": fov,
                                         "forward_vec": str(camera.get_transform().get_forward_vector()),
                                         "location": str(camera.get_transform().location),
                                         "transform": str(camera.get_transform()),
                                         "world_2_camera": str(camera.get_transform().get_inverse_matrix()),
                                         }
            for actor in other_actor_list:
                bb = actor.bounding_box
                bb_str = str(bb.extent)+'@'+str(bb.location)+'@'+str(bb.rotation)
                world_vertices = bb.get_world_vertices(actor.get_transform())
                world_vertices = str([str(i) for i in world_vertices])
                location = str(actor.get_location())
                velocity = str(actor.get_velocity())
                acceleration = str(actor.get_acceleration())
                angular_velocity = str(actor.get_angular_velocity())
                transform = str(actor.get_transform())
                # print(actor.id)

                this_frame_info[actor.id] = {"type_id": actor.type_id,
                                             "bb_str": bb_str,
                                             "world_vertices": world_vertices,
                                             "location": location,
                                             "velocity": velocity,
                                             "acceleration": acceleration,
                                             "angular_velocity": angular_velocity,
                                             "transform": transform,
                                             }
                # assert location == str(actor.get_transform().location)
            # print(this_frame_info)
            image.save_to_disk(f'{args.path}/{args.map}/{args.weather}'+'/%06d.png' % image.frame)
            
            with open(f'{args.path}/{args.map}/{args.weather}'+'/%06d.json' % image.frame, 'w') as f:
                json.dump(this_frame_info, f, indent=4, ensure_ascii=False)
            done_dump_flag = True
            camera_frame_counter += 1
            if camera_frame_counter == ratio:
                print(f'First frame at {image.frame}')
            if camera_frame_counter == seconds_lasting*sim_FPS:
                print(f'Last frame at {image.frame}')
            # frames_actor_info[image.frame] = this_frame_info

        # Wait for the ego vehicle to operate normally
        for _ in range(sim_FPS*5):
            tick_with_spectator(world, vehicle.get_transform(), spectator)
        time.sleep(1)
        camera.listen(save_image_to_disk)
        tick_with_spectator(world, vehicle.get_transform(), spectator)


        while True:
            if done_dump_flag:
                done_dump_flag = False
                tick_with_spectator(world, vehicle.get_transform(), spectator)
            if camera_frame_counter >= seconds_lasting*sim_FPS:
                break
        # with open(f'/home/ruoyao/test_physense_carla_syn/{args.map}'+'/frames_actor_info.json', 'w') as f:
        #     json.dump(frames_actor_info, f)
        
        # for i in range(100*5):
        #     world_snapshot = world.wait_for_tick()


    finally:
        print('\ndestroying %d vehicles' % len(vehicles_list))
        client.apply_batch([carla.command.DestroyActor(x) for x in vehicles_list])

        # stop walker controllers (list is [controller, actor, controller, actor ...])
        for i in range(0, len(all_id), 2):
            all_actors[i].stop()

        print('\ndestroying %d walkers' % len(walkers_list))
        client.apply_batch([carla.command.DestroyActor(x) for x in all_id])

        time.sleep(0.5)
        
        print('destroying actors')
        camera.destroy()
        client.apply_batch([carla.command.DestroyActor(x) for x in actor_list])
        print('done.')


if __name__ == '__main__':

    main()
